/**
 * Generates the committed homepage outputs.
 *
 *   docs/converter.js          from src/site.ts (the shipping Markdown converter)
 *   docs/index.html            site list block, from docs/sites.json
 *   SUPPORTED_SITES.md         site list block, from docs/sites.json
 *   README.md                  site summary block, from docs/sites.json
 *   LIBRARY.md                 extractor count
 *
 * Usage: tsx build/site.ts [--check]
 * With --check, nothing is written and a stale output is an error.
 */

import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getAvailableExtractorIds } from '../src/library/loaders';

interface Site { id: string; name: string; captures: string }
interface Category { category: string; sites: Site[] }

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes('--check');

const catalog = JSON.parse(readFileSync(join(ROOT, 'docs/sites.json'), 'utf8')) as Category[];
const total = catalog.reduce((sum, { sites }) => sum + sites.length, 0);

function assertCatalogMatchesExtractors(): void {
  const listed = catalog.flatMap(({ sites }) => sites.map(({ id }) => id));
  const available = getAvailableExtractorIds() as readonly string[];
  const duplicate = listed.filter((id, index) => listed.indexOf(id) !== index);
  const missing = available.filter((id) => !listed.includes(id));
  const unknown = listed.filter((id) => !available.includes(id));
  if (duplicate.length || missing.length || unknown.length) {
    throw new Error(`docs/sites.json does not match the extractor list: ${JSON.stringify({ missing, unknown, duplicate })}`);
  }
}

function escapeHtml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function slug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function renderHtml(): string {
  return catalog.map(({ category, sites }) => [
    `          <section class="site-group" data-group="${slug(category)}">`,
    `            <h3>${escapeHtml(category)} <span class="site-count">${sites.length}</span></h3>`,
    '            <ul>',
    ...sites.map(({ id, name, captures }) => (
      `              <li data-extractor="${id}"><strong>${escapeHtml(name)}</strong> <span>${escapeHtml(captures)}</span></li>`
    )),
    '            </ul>',
    '          </section>',
  ].join('\n')).join('\n');
}

function renderMarkdown(): string {
  return catalog.map(({ category, sites }) => [
    `## ${category}`,
    '',
    '| Site | What you get |',
    '| --- | --- |',
    ...sites.map(({ name, captures }) => `| **${name}** | ${captures} |`),
  ].join('\n')).join('\n\n');
}

function renderSummary(): string {
  return [
    '| Category | Sites |',
    '| --- | --- |',
    ...catalog.map(({ category, sites }) => `| **${category}** | ${sites.map(({ name }) => name).join(', ')} |`),
  ].join('\n');
}

function replaceBlock(file: string, name: string, content: string): string {
  const path = join(ROOT, file);
  const source = readFileSync(path, 'utf8');
  const start = `<!-- ${name}:start -->`;
  const end = `<!-- ${name}:end -->`;
  const from = source.indexOf(start);
  const to = source.indexOf(end);
  if (from < 0 || to < from) throw new Error(`${file} has no ${name} block`);
  const indent = /[ \t]*$/.exec(source.slice(0, to))?.[0] ?? '';
  return `${source.slice(0, from + start.length)}\n${content}\n${indent}${source.slice(to)}`;
}

/** Keep every stated extractor count in step with the catalog. */
function replaceCounts(source: string): string {
  return source.replace(/(<!-- count -->)\d+(<!-- \/count -->)/g, `$1${total}$2`);
}

async function buildConverter(): Promise<string> {
  const result = await esbuild.build({
    entryPoints: [join(ROOT, 'src/site.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'CopyAsMarkdownSite',
    minify: true,
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    banner: { js: '/* Generated by pnpm build:site from src/core/markdown.ts. Do not edit. */' },
  });
  return result.outputFiles[0].text;
}

assertCatalogMatchesExtractors();

const outputs: Array<[file: string, content: string]> = [
  ['docs/converter.js', await buildConverter()],
  ['docs/index.html', replaceCounts(replaceBlock('docs/index.html', 'sites', renderHtml()))],
  ['SUPPORTED_SITES.md', replaceCounts(replaceBlock('SUPPORTED_SITES.md', 'sites', `\n${renderMarkdown()}\n`))],
  ['LIBRARY.md', replaceCounts(readFileSync(join(ROOT, 'LIBRARY.md'), 'utf8'))],
  ['README.md', replaceCounts(replaceBlock('README.md', 'sites', `\n${renderSummary()}\n`))],
];

const stale: string[] = [];
for (const [file, content] of outputs) {
  const path = join(ROOT, file);
  let current = '';
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    // The converter bundle does not exist before the first build.
  }
  if (current === content) continue;
  if (check) stale.push(file);
  else writeFileSync(path, content);
}

if (stale.length) {
  console.error(`Stale generated files: ${stale.join(', ')}. Run pnpm build:site.`);
  process.exit(1);
}
console.log(`✅ Homepage outputs ${check ? 'are current' : 'written'} (${total} extractors)`);
